#!/usr/bin/env bash
# ============================================================================
# lib/credentials.sh — Secure credential generation, atomic write, per-site
# ============================================================================
# Sourced by install-frappe.sh. Never executed directly.
#
# SECURITY (BRD Section 58-59):
#   - CSPRNG via Python secrets module
#   - Per-site credential files in <bench>/credentials/
#   - Atomic write: temp → chmod 600 → verify → rename
#   - .gitignore generated to exclude credentials
#   - Never commit credentials to git

# ---- Load existing credentials ---------------------------------------------
# Reads a previously-generated credentials file so re-runs reuse the same
# passwords instead of generating new ones.

load_existing_credentials() {
  local cred_dir="${BENCH_DIR}/credentials"
  local cred_file="${cred_dir}/${SITE_NAME}.txt"

  # Also check legacy location (old installer format)
  local legacy_file="${BENCH_DIR}/frappe-credentials.txt"

  local source_file=""
  if [[ -f "${cred_file}" ]]; then
    source_file="${cred_file}"
  elif [[ -f "${legacy_file}" ]]; then
    source_file="${legacy_file}"
    ui_info "Found legacy credentials file, will migrate to new format."
  else
    return 0
  fi

  # Parse credentials using awk (format-aware)
  # Files written by installer <= 2.0.0 hold the MariaDB root password; it is
  # only used as a fallback login by detect_mariadb_admin_auth.
  MARIADB_LEGACY_ROOT_PASSWORD="$(awk '/MARIADB ROOT/{f=1} f&&/^Password:/{getline; gsub(/^[[:space:]]+|[[:space:]]+$/, ""); print; exit}' "${source_file}" 2>/dev/null || true)"
  ADMIN_PASSWORD="$(sed -n '/ADMINISTRATOR/,/^---/{/^Password:/{n;s/^[[:space:]]*//;p;q}}' "${source_file}" 2>/dev/null || true)"
  # Also try the FRAPPE ADMINISTRATOR header
  if [[ -z "${ADMIN_PASSWORD}" ]]; then
    ADMIN_PASSWORD="$(sed -n '/FRAPPE ADMINISTRATOR/,/^---/{/^Password:/{n;s/^[[:space:]]*//;p;q}}' "${source_file}" 2>/dev/null || true)"
  fi
  FRAPPE_DB_USER="$(sed -n '/DATABASE/,/^---/{/^Database User:/{n;s/^[[:space:]]*//;p;q}}' "${source_file}" 2>/dev/null || true)"
  # Also try "FRAPPE DATABASE" header
  if [[ -z "${FRAPPE_DB_USER}" ]]; then
    FRAPPE_DB_USER="$(sed -n '/FRAPPE DATABASE/,/^---/{/^Database User:/{n;s/^[[:space:]]*//;p;q}}' "${source_file}" 2>/dev/null || true)"
  fi
  FRAPPE_DB_PASSWORD="$(sed -n '/DATABASE/,/^---/{/^Database Password:/{n;s/^[[:space:]]*//;p;q}}' "${source_file}" 2>/dev/null || true)"
  if [[ -z "${FRAPPE_DB_PASSWORD}" ]]; then
    FRAPPE_DB_PASSWORD="$(sed -n '/FRAPPE DATABASE/,/^---/{/^Database Password:/{n;s/^[[:space:]]*//;p;q}}' "${source_file}" 2>/dev/null || true)"
  fi

  if [[ -n "${ADMIN_PASSWORD}" || -n "${MARIADB_LEGACY_ROOT_PASSWORD}" ]]; then
    ui_ok "Loaded existing credentials from ${source_file} (preserved, not regenerated)"
  fi
}

# ---- Write credentials file (atomic) ----------------------------------------

write_credentials_file() {
  local cred_dir="${BENCH_DIR}/credentials"
  mkdir -p "${cred_dir}"
  CREDENTIALS_FILE="${cred_dir}/${SITE_NAME}.txt"

  local db_server="local (root login unchanged — use: sudo mariadb -u root)"
  if [[ -n "${DB_HOST}" ]]; then
    db_server="${DB_HOST}:${DB_PORT:-3306} (external)"
  fi

  # Atomic write: temp file → chmod → verify → rename
  local tmp_file
  tmp_file="$(mktemp "${cred_dir}/.cred_XXXXXX")"

  cat > "${tmp_file}" <<EOF
============================================================
FRAPPE FRAMEWORK v${SELECTED_FRAPPE_VERSION} CREDENTIALS
============================================================

Installation Path:
  ${INSTALL_PATH}

Bench:
  ${BENCH_DIR}

Site:
  ${SITE_NAME}

URL:
  http://${SITE_NAME}:8000

------------------------------------------------------------
ADMINISTRATOR
------------------------------------------------------------

Username:
  Administrator

Password:
  ${ADMIN_PASSWORD}

------------------------------------------------------------
MARIADB ADMIN
------------------------------------------------------------

Server:
  ${db_server}

Username:
  ${MARIADB_ADMIN_USER}

Password:
  ${MARIADB_ADMIN_PASSWORD}

Option file (for: mariadb --defaults-extra-file=...):
  ${MARIADB_ACTIVE_CNF}

------------------------------------------------------------
FRAPPE DATABASE
------------------------------------------------------------

Database Name:
  ${FRAPPE_DB_NAME}

Database User:
  ${FRAPPE_DB_USER}

Database Password:
  ${FRAPPE_DB_PASSWORD}

------------------------------------------------------------
IMPORTANT
------------------------------------------------------------

Change these passwords after first login.
Do not commit this file to Git.

Generated by ${INSTALLER_NAME} v${INSTALLER_VERSION} on $(date -u '+%Y-%m-%d %H:%M:%S UTC').
EOF

  # Set permissions before renaming (atomic)
  chmod 600 "${tmp_file}"

  # Verify the file was written correctly
  if [[ ! -s "${tmp_file}" ]]; then
    fail_warning "Credential file write verification failed."
    rm -f "${tmp_file}"
    return 1
  fi

  # Atomic rename
  mv -f "${tmp_file}" "${CREDENTIALS_FILE}"

  # Ensure .gitignore excludes credentials
  _ensure_credentials_gitignore

  ui_ok "Credentials saved: ${CREDENTIALS_FILE} (chmod 600)"
}

# ---- Ensure .gitignore covers credentials -----------------------------------

_ensure_credentials_gitignore() {
  local gitignore="${BENCH_DIR}/.gitignore"

  # Create or update .gitignore
  if [[ ! -f "${gitignore}" ]]; then
    cat > "${gitignore}" <<'EOF'
# Frappe Installer — never commit credentials
credentials/
*.credentials.txt
frappe-credentials.txt
EOF
    return 0
  fi

  # Check if credentials/ is already in .gitignore
  if ! grep -qF "credentials/" "${gitignore}" 2>/dev/null; then
    echo "" >> "${gitignore}"
    echo "# Frappe Installer — never commit credentials" >> "${gitignore}"
    echo "credentials/" >> "${gitignore}"
  fi
}
